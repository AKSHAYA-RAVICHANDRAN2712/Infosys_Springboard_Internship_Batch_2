create table if not exists clinical_guideline (
  id bigint generated by default as identity primary key,
  code varchar(100) not null unique,
  name varchar(255) not null,
  condition_name varchar(255) not null,
  description varchar(1000),
  version varchar(50),
  status varchar(30) default 'ACTIVE'
);
create table if not exists guideline_rule (
  id bigint generated by default as identity primary key,
  guideline_id bigint not null references clinical_guideline(id),
  rule_code varchar(100) not null,
  rule_type varchar(100) not null,
  rule_description varchar(1000) not null,
  threshold double precision,
  unit varchar(50),
  priority integer default 1,
  active boolean default true
);
create table if not exists compliance_result (
  id bigint generated by default as identity primary key,
  patient_id bigint,
  care_plan_id bigint,
  guideline_code varchar(100),
  status varchar(30) not null,
  violations varchar(3000),
  warnings varchar(3000),
  checked_at timestamp not null
);
